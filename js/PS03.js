// Loop
// For loop
console.log("For loop-");
for (let i = 1; i <= 5; i++) {
  console.log("Hello  World!");
}

// while loop
console.log("While loop-");
let j = 1;
while (j <= 5) {
  console.log("Hello World!");
  j++;
}

// do-while loop
console.log("Do-while loop-");
let i = 1;
do {
  console.log("Hello World!");
  i++;
} while (i <= 5);
